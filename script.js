// ج. تحديث الـ SEO (Meta Tags & Schema) ديناميكياً
function updateSEO(title, desc, urlPart) {
  document.title = `${title} | مركز الصيانة المعتمد TM`;
  const ogTitle = document.getElementById('og-title'); if(ogTitle) ogTitle.content = title;
  const ogDesc = document.getElementById('og-desc'); if(ogDesc) ogDesc.content = desc;
  const canonical = document.getElementById('canonical-url'); if(canonical) canonical.href = `https://yourwebsite.com/${urlPart}`;
  
  const schemaScript = document.getElementById('dynamic-schema');
  if(schemaScript) {
    try {
      let schema = JSON.parse(schemaScript.innerText);
      if(Array.isArray(schema['@graph'])) {
        schema['@graph'][0].name = `${title} - مركز الصيانة المعتمد TM`;
        schemaScript.innerText = JSON.stringify(schema);
      }
    } catch(e) { console.log('Schema Update Error:', e); }
  }
}

